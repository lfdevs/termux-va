/* The probe resolution must match the SPS of the embedded stream: the
 * daemon configures MediaCodec with the handshake w/h, and whether a
 * mismatch still decodes depends on adaptive-playback - not something to
 * rely on.  96x96 is the lower bound of the hardware range, so anything
 * smaller would be rejected with status=3, and anything larger only makes
 * each frame bigger and the probe slower. */
#define PROBE_W          96
#define PROBE_H          96

#define FMTDESC_BYTES     32

/* Rational upper bound on a downlink frame size, used ONLY to detect
 * protocol desync - it is not a protocol constraint.
 * Do NOT validate against MAX_FRAME (8MB): that cap only bounds UPLINK
 * units.  A single 4K NV12 frame is 12441600 bytes, far above 8MB; using
 * MAX_FRAME here would reject perfectly good frames. */
#define FRAME_SANITY_MAX  (64u * 1024u * 1024u)

/* After the first frame arrives, wait this much longer purely to finish
 * counting (5 IDR units usually yield 5 frames).  Health only needs 1
 * frame, so this grace window can be cut short by the hard deadline. */
#define TAIL_GRACE_MS     250

#define DISCARD_CHUNK     (64u * 1024u)

/* io_all return values: "timed out" and "peer closed" are separated because
 * they mean completely different things in the 0-frames diagnosis
 * (timeout = collapsed throughput; EOF = the daemon abandoned the session). */
#define IO_OK       0
#define IO_ERR     (-1)   /* real error, or the peer died mid-message */
#define IO_TIMEOUT (-2)
#define IO_EOF     (-3)   /* peer closed exactly at a message boundary - a
                           * normal end of stream */

