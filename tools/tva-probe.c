static long long now_ms(void)
{
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (long long)ts.tv_sec * 1000 + ts.tv_nsec / 1000000;
}

/* Full read/write with an ABSOLUTE deadline: a watchdog must never block
 * forever on a half-dead peer.  A single absolute deadline is used instead
 * of a per-call relative timeout - otherwise "3 seconds per step" adds up
 * to tens of seconds and the probe itself eats the watchdog's polling
 * interval. */
static int io_all(int fd, void *buf, size_t len, int writing, long long deadline)
{
    unsigned char *p = buf;
    size_t done = 0;
    while (done < len) {
        long long left = deadline - now_ms();
        if (left <= 0)
            return IO_TIMEOUT;
        struct pollfd pfd = { .fd = fd, .events = writing ? POLLOUT : POLLIN };
        int pr = poll(&pfd, 1, (int)left);
        if (pr == 0)
            return IO_TIMEOUT;
        if (pr < 0) {
            if (errno == EINTR)
                continue;
            return IO_ERR;
        }
        ssize_t n = writing ? write(fd, p + done, len - done)
                            : read(fd, p + done, len - done);
        if (n > 0) {
            done += (size_t)n;
            continue;
        }
        if (n == 0)
            return done ? IO_ERR : IO_EOF;   /* half a message = fault; boundary = normal end */
        if (errno == EINTR || errno == EAGAIN)
            continue;
        return IO_ERR;
    }
    return IO_OK;
}

static int read_all(int fd, void *buf, size_t len, long long deadline)
{
    return io_all(fd, buf, len, 0, deadline);
}

/* The write path never modifies the buffer; the const cast lives here once. */
static int write_all(int fd, const void *buf, size_t len, long long deadline)
{
    return io_all(fd, (void *)(uintptr_t)buf, len, 1, deadline);
}

static const char *io_why(int rc)
{
    switch (rc) {
    case IO_TIMEOUT: return "timeout";
    case IO_EOF:     return "peer closed";
    default:         return "I/O error";
    }
}

/* Locate the next 3-byte start code 00 00 01 (the last 3 bytes of a 4-byte
 * start code also match); returns len when none is found. */
static size_t next_start_code(const unsigned char *d, size_t len, size_t from)
{
    for (size_t i = from; i + 2 < len; i++)
        if (d[i] == 0 && d[i + 1] == 0 && d[i + 2] == 1)
            return i;
    return len;
}

/*
 * Split the embedded stream into single NALUs at start codes and send each
 * one with its own 4-byte length prefix.
 *
 * NEVER send the stream as one blob.  The protocol carries exactly ONE NALU
 * per length prefix, and the daemon relies on per-unit type detection to
 * recognize SPS(7)/PPS(8) and accumulate them into the CSD (submitted with
 * FLAG_CODEC_CONFIG, which produces no frames).  One giant blob would be
 * treated as a single VCL unit, leaving the decoder without parameter sets
 * and producing zero frames - a false positive for exactly the failure this
 * probe exists to catch.  NALUs MUST keep their start codes (3 or 4 bytes
 * both fine); the daemon's nalu_type() skips it.
 */
static int send_stream(int fd, long long deadline, unsigned *nalus, int *rc_out)
{
    const unsigned char *d = probe_stream;
    const size_t len = sizeof(probe_stream);
    size_t pos = next_start_code(d, len, 0);

    *nalus = 0;
    while (pos < len) {
        size_t next = next_start_code(d, len, pos + 3);
        size_t end = next;
        /* Strip trailing 0x00 bytes: they are either the head of the next
         * 4-byte start code or trailing_zero_8bits.  An RBSP always ends
         * with a stop bit (a non-zero byte), so stripping zeros never
         * touches semantics.  Not stripping would attach the next start
         * code's leading zeros to the previous NALU - most decoders
         * tolerate it, but there is no reason to risk it. */
        while (end > pos + 3 && d[end - 1] == 0)
            end--;

        uint32_t nl = htonl((uint32_t)(end - pos));
        int rc = write_all(fd, &nl, 4, deadline);
        if (rc == IO_OK)
            rc = write_all(fd, d + pos, end - pos, deadline);
        if (rc != IO_OK) {
            *rc_out = rc;
            return -1;
        }
        (*nalus)++;
        pos = next;
    }
    return 0;
}

/*
 * Read the downlink and count real frames.
 *
 * One parser covers both message kinds: a frame-size field equal to the
 * sentinel 0xFFFFFFFF means a format descriptor block (a legal frame size
 * can never take that value), otherwise it is a frame.  Word 2 of the
 * format block header carries capability flags; CAP_FRAME_PTS means every
 * later frame header has an extra 4th field (the input unit index).  That
 * flag is the ONLY correct discriminator - never guess.
 */
static int collect_frames(int fd, long long hard_deadline, unsigned *frames,
                          int *rc_out, const char **desync)
{
    uint32_t caps = 0;
    unsigned char sink[DISCARD_CHUNK];

    *frames = 0;
    for (;;) {
        /* Health is decidable after the first frame; the remaining time
         * only completes the count, so switch to a much shorter deadline
         * and never eat the watchdog's whole polling interval. */
        long long deadline = hard_deadline;
        if (*frames > 0) {
            long long grace = now_ms() + TAIL_GRACE_MS;
            if (grace < deadline)
                deadline = grace;
        }

        uint32_t head[3];
        int rc = read_all(fd, head, sizeof(head), deadline);
        if (rc != IO_OK) {
            if (*frames > 0)
                return 0;             /* frames already seen: any ending is fine */
            *rc_out = rc;
            return -1;
        }

        uint32_t fsz = ntohl(head[2]);

        if (fsz == FMTDESC_SENTINEL) {
            unsigned char body[FMTDESC_BYTES];
            rc = read_all(fd, body, sizeof(body), deadline);
            if (rc != IO_OK) {
                if (*frames > 0)
                    return 0;
                *rc_out = rc;
                return -1;
            }
            caps = ntohl(head[1]);
            continue;
        }

        if (fsz == SHMFRAME_SENTINEL) {
            /* The probe requests inline delivery (xfer=0) and the daemon
             * only downgrades, never upgrades - an SHM notification here
             * can only be protocol desync; parsing further is pointless. */
            *desync = "SHM frame notification in inline mode";
            *rc_out = IO_ERR;
            return -1;
        }

        if (caps & CAP_FRAME_PTS) {
            uint32_t pts;
            rc = read_all(fd, &pts, sizeof(pts), deadline);
            if (rc != IO_OK) {
                if (*frames > 0)
                    return 0;
                *rc_out = rc;
                return -1;
            }
        }

        if (fsz > FRAME_SANITY_MAX) {
            *desync = "absurd downlink frame size, protocol desync";
            *rc_out = IO_ERR;
            return -1;
        }

        size_t rem = fsz;
        while (rem > 0) {
            size_t ch = rem > sizeof(sink) ? sizeof(sink) : rem;
            rc = read_all(fd, sink, ch, deadline);
            if (rc != IO_OK) {
                if (*frames > 0)
                    return 0;
                *rc_out = rc;
                return -1;
            }
            rem -= ch;
        }

        if (fsz > 0) {
            /* Only "non-sentinel message with size > 0" counts as a real
             * frame - format blocks and empty messages do not. */
            (*frames)++;
            if (*frames >= 64)
                return 0;             /* enough; do not run with the daemon forever */
        }
    }
}

static int connect_endpoint(const struct sockaddr_un *ua)
{
    int fd = socket(AF_UNIX, SOCK_STREAM | SOCK_CLOEXEC, 0);
    if (fd < 0) {
        fprintf(stderr, "probe: socket(): %s\n", strerror(errno));
        return -1;
    }
    if (connect(fd, (const struct sockaddr *)ua, sizeof(*ua)) != 0) {
        /* With a directory-level mount this usually means the daemon really
         * is not running; with a file-level mount it can also mean the mount
         * pins a dead inode (fix the mount, do not restart the daemon). */
        fprintf(stderr, "probe: connect failed: %s\n", strerror(errno));
        close(fd);
        return -1;
    }
    return fd;
}

/* TVA: same resolution order as the daemon (resolve_socket_path there). */
static const char *resolve_endpoint(char *buf, size_t bufsz)
{
    const char *env_sock = getenv("TERMUX_VA_SOCKET");
    if (env_sock && *env_sock)
        return env_sock;

    const char *env_dir = getenv("TERMUX_VA_SOCKET_DIR");
    if (env_dir && *env_dir) {
        snprintf(buf, bufsz, "%s/%s", env_dir, TVA_SOCK_NAME);
        return buf;
    }

    const char *tmp = getenv("TMPDIR");
    if (!tmp || !*tmp || strcmp(tmp, "/data/local/tmp") == 0) {
        struct stat st;
        if (stat("/tmp", &st) == 0 && S_ISDIR(st.st_mode))
            tmp = "/tmp";
        else
            tmp = "/data/data/com.termux/files/usr/tmp";
    }
    snprintf(buf, bufsz, "%s/%s/%s", tmp, TVA_SOCKET_DIR_NAME, TVA_SOCK_NAME);
    return buf;
}

int main(int argc, char **argv)
{
    char resolved[512];
    /* TVA: the endpoint argument is optional; when omitted, the daemon's
     * own resolution order is used. */
    const char *path = (argc > 1) ? argv[1] : resolve_endpoint(resolved, sizeof(resolved));
    int timeout_ms = (argc > 2) ? atoi(argv[2]) : 3000;
    if (timeout_ms <= 0)
        timeout_ms = 3000;
    if (!path || !*path) {
        fprintf(stderr, "usage: tva-probe [socket path] [timeout ms, default 3000]\n");
        return 3;
    }

    /* A real decode is slower than a bare handshake, but five 96x96 IDRs
     * complete in tens of milliseconds; the caller still caps everything
     * with one argument - all I/O shares this single absolute deadline. */
    long long t0 = now_ms();
    long long deadline = t0 + timeout_ms;

    struct stat st;
    if (stat(path, &st) != 0) {
        fprintf(stderr, "probe: endpoint missing %s: %s\n", path, strerror(errno));
        return 1;
    }

    struct sockaddr_un ua;
    memset(&ua, 0, sizeof(ua));
    ua.sun_family = AF_UNIX;
    if (strlen(path) >= sizeof(ua.sun_path)) {
        fprintf(stderr, "probe: path too long\n");
        return 3;
    }
    memcpy(ua.sun_path, path, strlen(path));

    int fd = connect_endpoint(&ua);
    if (fd < 0)
        return 1;

    uint32_t hello[6] = {
        htonl(HELLO_MAGIC), htonl(HELLO_VERSION), htonl(0),   /* codec 0 = H.264 */
        htonl(PROBE_W), htonl(PROBE_H), htonl(0)              /* xfer 0 = inline */
    };
    /* Always request inline delivery: SHM would need a second abstract
     * socket to receive the memfd, which adds a fragile path without
     * improving the "does it produce frames" criterion. */
    if (write_all(fd, hello, sizeof(hello), deadline) != IO_OK) {
        fprintf(stderr, "probe: sending handshake failed/timed out\n");
        close(fd);
        return 2;
    }

    uint32_t head[3];
    if (read_all(fd, head, sizeof(head), deadline) != IO_OK) {
        fprintf(stderr, "probe: no handshake response/timed out (process may be alive but not serving)\n");
        close(fd);
        return 2;
    }
    uint32_t status = ntohl(head[0]);
    uint32_t nlen_w = ntohl(head[2]);
    int legacy_v2 = 0;

    if (status == 1) {
        /* An old daemon with strict version checking rejects v3.  It is
         * still healthy, just old - retry with v2 so the watchdog does not
         * kill a good daemon.  A v2 response has no endpoint extension;
         * skip the inode reconciliation in that round. */
        close(fd);
        fd = connect_endpoint(&ua);
        if (fd < 0)
            return 1;
        hello[1] = htonl(2u);
        if (write_all(fd, hello, sizeof(hello), deadline) != IO_OK ||
            read_all(fd, head, sizeof(head), deadline) != IO_OK) {
            fprintf(stderr, "probe: v2 downgrade retry failed/timed out\n");
            close(fd);
            return 2;
        }
        status = ntohl(head[0]);
        nlen_w = ntohl(head[2]);
        legacy_v2 = 1;
    }

    if (status != 0) {
        /* A non-zero status response is always a bare 12 bytes, followed by
         * a close - there is nothing more to read. */
        fprintf(stderr, "probe: daemon rejected handshake status=%u\n", status);
        close(fd);
        return 2;
    }

    uint32_t xfer = ntohl(head[1]);
    if (xfer != 0) {
        /* We requested inline and the daemon granted SHM: frames will not
         * come back over this connection, so the session can never produce
         * frames - report "not serving" instead of burning a timeout. */
        fprintf(stderr, "probe: daemon returned non-inline transport %u, probe cannot collect frames\n", xfer);
        close(fd);
        return 2;
    }

    /* With the v3 extension present, reconcile inodes on the side: a
     * mismatch means this path does not lead to the endpoint that answered,
     * and restarting the daemon cannot fix it (it is a mount/configuration
     * problem) - hence the dedicated exit code 7.
     * Compare against stat(path), NOT fstat on the connection fd - the
     * latter is the socket's anonymous inode and has nothing to do with the
     * listening endpoint. */
    int have_ep = 0;
    unsigned long long ep_dev = 0, ep_ino = 0;
    if (!legacy_v2 && (nlen_w >> 31)) {
        uint32_t ext[4];
        if (read_all(fd, ext, sizeof(ext), deadline) == IO_OK) {
            ep_dev = ((unsigned long long)ntohl(ext[0]) << 32) | ntohl(ext[1]);
            ep_ino = ((unsigned long long)ntohl(ext[2]) << 32) | ntohl(ext[3]);
            if (ep_dev != (unsigned long long)st.st_dev ||
                ep_ino != (unsigned long long)st.st_ino) {
                fprintf(stderr, "probe: endpoint inode mismatch "
                        "stat(dev=%llu,ino=%llu) != daemon(dev=%llu,ino=%llu)\n",
                        (unsigned long long)st.st_dev,
                        (unsigned long long)st.st_ino, ep_dev, ep_ino);
                close(fd);
                return 7;
            }
            have_ep = 1;
        } else {
            fprintf(stderr, "probe: endpoint extension read failed, skipping inode reconciliation\n");
        }
    }

    /* In inline mode the name length is always 0; if it ever is not
     * (protocol evolution/anomaly), those bytes must be consumed before
     * reading frames or every later header is misaligned. */
    uint32_t nlen = nlen_w & 0x7FFFFFFFu;
    if (nlen > 0 && nlen <= 256) {
        unsigned char name[256];
        if (read_all(fd, name, nlen, deadline) != IO_OK) {
            fprintf(stderr, "probe: failed to read endpoint name\n");
            close(fd);
            return 2;
        }
    } else if (nlen > 256) {
        fprintf(stderr, "probe: abnormal handshake name length %u\n", nlen);
        close(fd);
        return 2;
    }

    /* ---- Handshake fully succeeded.  Any "no frames" from here on is the
     * newer failure class (exit code 8). ---- */
    unsigned nalus = 0, frames = 0;
    int io_rc = IO_ERR;
    const char *desync = NULL;

    if (send_stream(fd, deadline, &nalus, &io_rc) != 0) {
        /* A stalled/broken uplink is itself the scene of that failure
         * class: with collapsed throughput the daemon cannot read and our
         * write times out; with an abandoned session the write gets EPIPE. */
        fprintf(stderr, "probe: unhealthy, handshake ok but sending the stream failed (timeout %dms, "
                "%u NALUs sent, reason=%s)\n",
                timeout_ms, nalus, io_why(io_rc));
        close(fd);
        return 8;
    }

    /* Shutting the write end triggers the daemon's EOS so the decoder
     * emits everything it holds.  The probe is a one-shot session and has
     * no use for the reversible drain (the length-0 path) - that exists for
     * long-lived sessions, and flush destroys the reference chain, a pure
     * side effect for a probe. */
    shutdown(fd, SHUT_WR);

    if (collect_frames(fd, deadline, &frames, &io_rc, &desync) != 0 || frames == 0) {
        if (desync)
            fprintf(stderr, "probe: unhealthy, downlink parse failure: %s (%u NALUs sent)\n",
                    desync, nalus);
        else
            fprintf(stderr, "probe: unhealthy, handshake ok but 0 frames returned (timeout %dms, "
                    "%u NALUs sent, reason=%s)\n",
                    timeout_ms, nalus, io_why(io_rc));
        close(fd);
        return 8;
    }

    /* NALUs in != frames out is NOT an equation to check: SPS/PPS produce no
     * frames and the decoder has queuing/reorder latency.  The only
     * criterion is at least one real returned frame. */
    if (legacy_v2)
        printf("probe: healthy frames=%u (protocol v2, legacy daemon)\n", frames);
    else if (have_ep)
        printf("probe: healthy frames=%u dev=%llu ino=%llu\n", frames, ep_dev, ep_ino);
    else
        printf("probe: healthy frames=%u (no endpoint extension)\n", frames);

    close(fd);
    return 0;
}
